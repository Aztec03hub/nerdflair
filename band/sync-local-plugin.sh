#!/usr/bin/env bash
# sync-local-plugin.sh - publish band/ as the user-level plugin nerdflair-band@local.
#
# Until this was installed the band existed only as a dev mod, which loads in
# the ONE session that made it ("loaded from this session's mods folder"), so
# no other session had the hover band or the Remote Control pill.
#
# The marketplace entry must be a real directory, not a link back into this
# repo: a symlinked source resolves outside the marketplace and the plugin
# reports "Path escapes plugin directory" for its hooks module. So the files
# the plugin needs are COPIED, and this script is the one way to refresh them.
# Re-run it after changing band/hooks or band/popup.sh.
#
# VERSION STAMP. `claude plugin update` keys its cache on the plugin's version, so
# with plugin.json fixed at 0.1.0 an update after a code change was a silent no-op:
# the running copy stayed the one from the day it was first installed (2026-10-19:
# a 9 Oct copy was still drawing a bug fixed on 19 Oct). The copy this script
# publishes therefore carries 0.1.0-<8 hex of its own content>, so any change to
# what ships gives Claude Code a new version to fetch, and no change gives the
# same one. The repo's plugin.json stays at 0.1.0.
#
# `--stamp` prints the version this checkout would publish. `--check` changes nothing: it says whether the published
# copy matches this checkout and exits 1 when it does not.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DEST="${NERDFLAIR_PLUGIN_DEST:-$HOME/.claude/local-marketplace/plugins/nerdflair-band}"
DEST="${DEST%/}"   # a trailing slash on a symlink would defeat the -L test below
if [[ -z "$DEST" || "$DEST" == "/" ]]; then echo "sync: refusing an empty or root destination" >&2; exit 2; fi
INSTALLED_JSON="${NERDFLAIR_INSTALLED_PLUGINS:-$HOME/.claude/plugins/installed_plugins.json}"

# The content that ships, in a fixed order, hashed. types/ is engine-generated
# and not part of the identity.
content_stamp() {
  cat "$HERE/.claude-plugin/plugin.json" "$HERE/hooks/hooks.json" "$HERE/hooks/register.tsx" "$HERE/popup.sh" "$HERE/tsconfig.json" \
    | python3 -c 'import sys,hashlib
raw=sys.stdin.buffer.read()
print(hashlib.sha256(raw).hexdigest()[:8])'
}
STAMP="$(content_stamp)"
VERSION="0.1.0-$STAMP"

if [[ "${1:-}" == "--stamp" ]]; then echo "$VERSION"; exit 0; fi
if [[ "${1:-}" == "--check" ]]; then
  # Two copies can be stale: the published one (marketplace) and the one Claude Code actually loads
  # (installed_plugins.json, the cache). The 2026-10 bug was the second, so both are compared.
  ver_of() { python3 -c 'import sys,json
try: print(json.load(open(sys.argv[1])).get("version",""))
except Exception: print("")' "$1" 2>/dev/null; }
  inst_ver() { python3 -c 'import sys,json
try:
    d = json.load(open(sys.argv[1])); d = d.get("plugins", d)
    print((d.get("nerdflair-band@local") or [{}])[0].get("version", ""))
except Exception: print("")' "$1" 2>/dev/null; }
  have="$(ver_of "$DEST/.claude-plugin/plugin.json")"
  loaded="$(inst_ver "$INSTALLED_JSON")"
  rc=0
  if [[ "$have" != "$VERSION" ]]; then
    echo "nerdflair-band: published copy is STALE (has '${have:-none}', this checkout is $VERSION). Run band/sync-local-plugin.sh, then /reload-plugins or restart sessions." >&2; rc=1
  fi
  if [[ "$loaded" != "$VERSION" ]]; then
    echo "nerdflair-band: the INSTALLED plugin is STALE (Claude Code has '${loaded:-none}', this checkout is $VERSION). Run band/sync-local-plugin.sh, then /reload-plugins or restart sessions." >&2; rc=1
  fi
  (( rc == 0 )) && echo "nerdflair-band: published and installed copies are current ($VERSION)"
  exit "$rc"
fi

if [[ -L "$DEST" ]]; then
  rm "$DEST"                       # a link into the repo: replace, never follow
fi
mkdir -p "$DEST/.claude-plugin" "$DEST/hooks"
python3 - "$HERE/.claude-plugin/plugin.json" "$DEST/.claude-plugin/plugin.json" "$VERSION" <<'PY'
import sys, json
src, dst, version = sys.argv[1:4]
d = json.load(open(src))
d["version"] = version
import os
tmp = dst + ".tmp"
with open(tmp, "w") as fh:
    json.dump(d, fh, indent=2)
    fh.write("\n")
os.replace(tmp, dst)
PY
# Replace the types directory whole: cp -r over it would leave behind files
# that were deleted in the repo.
[[ -d "$DEST/.claude-plugin/types" && ! -L "$DEST/.claude-plugin/types" ]] && rm -rf -- "$DEST/.claude-plugin/types"
# types/ is generated by the engine and git-ignored: absent in a fresh checkout or worktree.
[[ -d "$HERE/.claude-plugin/types" ]] && cp -rf "$HERE/.claude-plugin/types" "$DEST/.claude-plugin/"
cp -f "$HERE/hooks/hooks.json" "$HERE/hooks/register.tsx" "$DEST/hooks/"
cp -f "$HERE/popup.sh" "$HERE/tsconfig.json" "$DEST/"

# Not `if claude plugin list | python3 ...`: inside an if condition set -e and
# pipefail are off, so a failing `claude plugin list` (crash, not logged in, bad
# JSON) would read as "not installed" and run install. Fail loudly instead.
list=$(claude plugin list --json) || { echo "sync: 'claude plugin list --json' failed; not guessing whether the plugin is installed" >&2; exit 1; }
if present=$(python3 -c '
import sys, json
sys.exit(0 if any(p["id"] == "nerdflair-band@local" for p in json.load(sys.stdin)) else 1)' <<<"$list" 2>&1); then
  claude plugin update nerdflair-band@local
else
  rc=$?
  # python's exit 1 is "not in the list"; anything else (a traceback, bad JSON) is a failure
  if (( rc != 1 )) || [[ -n "$present" ]]; then echo "sync: could not read the plugin list: ${present##*$'\n'}" >&2; exit 1; fi
  claude plugin install nerdflair-band@local
fi

claude plugin list --json | python3 -c '
import sys, json
for p in json.load(sys.stdin):
    if p["id"] == "nerdflair-band@local":
        print("nerdflair-band@local enabled=%s errors=%s" % (p["enabled"], p.get("errors")))
        sys.exit(1 if p.get("errors") else 0)
sys.exit("nerdflair-band@local is not installed")'
